// Files for the MOTIS container. They are written into its data folder by this server,
// so updating this image is enough to change how MOTIS runs.
import { config } from './config.ts'

export function motisConfigYaml(): string {
  return `# Generated by Takt. Changes are overwritten.
server:
  host: 0.0.0.0
  port: 8080
  web_folder: /ui
  n_threads: 4
osm: mdv.osm.pbf
timetable:
  first_day: TODAY
  num_days: 60
  railviz: false
  with_shapes: true
  # map-match every route onto OSM rails/roads (gtfs.de has no shapes.txt)
  route_shapes:
    mode: all
    cache_db_size: 8589934592
    n_threads: 4
  adjust_footpaths: true
  merge_dupes_intra_src: true
  link_stop_distance: 100
  update_interval: ${Math.max(20, config.rtActiveInterval)}
  http_timeout: 20
  incremental_rt_update: false
  max_footpath_length: 15
  default_transfer_time: 2
  datasets:
${config.datasets.map(d => `    ${d.tag}:
      path: ${d.tag}.gtfs.zip
      rt:
        - url: ${config.selfUrl}/rt/${d.tag}.pb
`).join('')}street_routing: true
osr_footpath: true
elevators: false
geocoding: true
reverse_geocoding: false
`
}

export function motisRunScript(): string {
  return `#!/bin/sh
# Generated by Takt. Runs inside the MOTIS container (command: sh /data/run.sh).
# Imports input/ into a new build folder whenever input/version changes,
# then switches the server over. The old server keeps running during an import.
cd /data
log() { echo "[run.sh] $(date '+%F %T') $*"; }
SPID=""
trap 'log stop; [ -n "$SPID" ] && kill $SPID; exit 0' TERM INT

while [ ! -f input/version ]; do log "waiting for input/version from the Takt container"; sleep 20 & wait $!; done

CUR=""
[ -f current ] && CUR=$(cat current)
[ -n "$CUR" ] && [ ! -f "build-$CUR/config.yml" ] && CUR=""

start() {
  log "start server build-$CUR"
  /motis server -d "build-$CUR" &
  SPID=$!
}

while true; do
  V=$(cat input/version)
  if [ "$V" != "$CUR" ]; then
    log "import $V"
    rm -rf "build-$V"
    if (cd input && /motis import -c config.yml -d "../build-$V"); then
      [ -n "$SPID" ] && kill $SPID && wait $SPID 2>/dev/null
      SPID=""
      OLD="$CUR"; CUR="$V"; echo "$CUR" > current
      [ -n "$OLD" ] && rm -rf "build-$OLD"
      log "import $V done"
    else
      log "import $V FAILED, keeping build-$CUR"
      rm -rf "build-$V"
      echo "$V" > failed
      while [ "$(cat input/version)" = "$V" ]; do
        if [ -z "$SPID" ] && [ -n "$CUR" ]; then start; fi
        sleep 60 & wait $!
      done
      continue
    fi
  fi
  if [ -z "$SPID" ] || ! kill -0 $SPID 2>/dev/null; then
    [ -n "$CUR" ] && start
  fi
  sleep 30 & wait $!
done
`
}
